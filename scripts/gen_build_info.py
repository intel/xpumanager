"""Generate xpum_build_info.h: git provenance plus build configuration.

Run as a build_always_stale custom_target so the recorded commit id can never go
stale the way a hand-edited macro does.  To avoid relinking on every no-op build,
the output is rewritten only when something other than the timestamp changed.

Every field degrades to a placeholder rather than failing the build: source
tarballs have no .git directory and no git binary.

Timestamps are emitted as epoch seconds and formatted by the C++ side, because
git's format-local renders in the build machine's zone -- one commit reported
different "UTC" times depending on where it was built.

Python floor is 3.9: meson runs this with its own interpreter, and the RHEL /
AlmaLinux 8.10 build images install meson under python3.9.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import time
from pathlib import Path

UNKNOWN = "unknown"
TIMESTAMP_MACRO = "XPUM_BUILD_TIMESTAMP_EPOCH"
#: Negative rather than 0, because SOURCE_DATE_EPOCH=0 is a valid timestamp that
#: must be reported rather than treated as "unknown". The C++ side omits the field.
UNAVAILABLE_EPOCH = -1


def parse_args():
    """Parse the build configuration meson passes on the command line."""
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--output", required=True, type=Path)
    p.add_argument("--source-root", required=True, type=Path)
    p.add_argument("--version", required=True)
    p.add_argument("--buildtype", default=UNKNOWN)
    p.add_argument("--platform", default=UNKNOWN)
    return p.parse_args()


def git(source_root: Path, *args: str) -> str:
    """Run git in @p source_root, returning "" on any failure.

    Absent git, or a directory that is not a repository, yields "" for every query
    rather than raising: a source tarball must still build.

    errors="replace" rather than the default strict decoder: git does not require ref
    names to be valid UTF-8, so `git describe` can return bytes that would otherwise
    raise UnicodeDecodeError -- a ValueError, which the handler below does not catch --
    and abort the build. A provenance string only needs to be deterministic, not
    faithful.
    """
    try:
        out = subprocess.run(
            ["git", "-C", str(source_root), *args],
            capture_output=True,
            check=True,
            encoding="utf-8",
            errors="replace",
        )
    except (OSError, subprocess.CalledProcessError):
        return ""
    return out.stdout.strip()


def as_epoch(value: str) -> int:
    """Parse epoch seconds, or UNAVAILABLE_EPOCH for anything that is not one.

    int() rather than str.isdigit(): build wrappers that inject SOURCE_DATE_EPOCH
    can leave surrounding whitespace or a leading "+", and rejecting those would
    silently fall back to the wall clock and break reproducible builds.
    """
    try:
        epoch = int(value)
    except ValueError:
        return UNAVAILABLE_EPOCH
    return epoch if epoch >= 0 else UNAVAILABLE_EPOCH


def define(name: str, value) -> str:
    """Render one #define; ints emit bare, strings quoted and escaped."""
    if isinstance(value, int):
        return "#define {} {}".format(name, value)
    escaped = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return '#define {} "{}"'.format(name, escaped)


def without_timestamp(text: str) -> str:
    """Drop the timestamp line so two renders can be compared for real changes."""
    return "\n".join(l for l in text.splitlines() if TIMESTAMP_MACRO not in l)


def main() -> int:
    """Render xpum_build_info.h, rewriting it only when its content changed.

    Returns 0 always: every field degrades to a placeholder instead of failing.
    """
    args = parse_args()
    run = lambda *a: git(args.source_root, *a)  # noqa: E731

    build_epoch = as_epoch(os.environ.get("SOURCE_DATE_EPOCH", ""))

    macros = [
        ("XPUM_BUILD_VERSION", args.version),
        ("XPUM_BUILD_DESCRIBE", run("describe", "--tags", "--dirty", "--always", "--long") or UNKNOWN),
        ("XPUM_BUILD_COMMIT", run("rev-parse", "--short=12", "HEAD") or UNKNOWN),
        ("XPUM_BUILD_TYPE", args.buildtype),
        ("XPUM_BUILD_PLATFORM", args.platform),
        ("XPUM_BUILD_COMMIT_EPOCH", as_epoch(run("log", "-1", "--format=%ct"))),
        (TIMESTAMP_MACRO, build_epoch if build_epoch != UNAVAILABLE_EPOCH else int(time.time())),
    ]

    text = "\n".join(
        [
            "/* Generated by scripts/gen_build_info.py -- do not edit. */",
            "#ifndef XPUM_BUILD_INFO_H",
            "#define XPUM_BUILD_INFO_H",
            "",
            *(define(name, value) for name, value in macros),
            "",
            "#endif // XPUM_BUILD_INFO_H",
            "",
        ]
    )

    # Rewriting with only a new timestamp would make ninja relink every object that
    # includes the header, on every build, for no new information.
    try:
        existing = args.output.read_text(encoding="utf-8")
    except OSError:
        existing = ""
    if without_timestamp(existing) != without_timestamp(text):
        args.output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
